// 면적·두께처럼 "필수 입력"이 아니라 안 건드려도 되는 선택 항목이다. 그래서 면적·두께
// 처럼 범위 밖일 때 가정값(assumed)으로 되돌리는 게 아니라 — 애초에 "가정"이라는 개념
// 자체가 없는 값이라 — 그냥 "빈 칸(0원)"과 똑같이 취급한다.
//
// 2026-09-30 지휘관 긴급 전달(중요 3) — 예전 판(직전 유효값을 그대로 쓴다)은 큰 결함이
// 있었다: 배송비 칸에 20000000을 "한 글자씩" 치는 동안(2→20→200→...→20000000) 칸이
// 범위(1,000만원)를 넘는 순간부터는 "치는 도중 거쳐 간 마지막 유효값"(예: 200만원)으로
// 계산해 버렸다. 그 200만원은 사용자가 실제로 넣으려던 값이 아니라 타이핑 중간에 잠깐
// 지나간 숫자일 뿐인데, 화면 하단 금액이 그 값 기준으로 조용히 바뀌고 공유 버튼까지
// 그대로 보여서 "계산기 금액 ≠ 공유 결과 금액" 사고로 이어졌다(공유 링크는 원래 form
// 값 2000만원 기준이라 결과 화면은 상한(1,000만원)으로 잘린 값이 나왔다).
//
// 고친 규칙: 범위를 벗어난 값은 "직전 값"이 아니라 **그냥 undefined(안 넣은 것)**로
// 계산에 넣는다. 사용자가 뜻한 적 없는 중간값을 계산에 쓰지 않는다 — 범위 밖이면
// 그 항목 없이(0원으로) 계산하고, 칸 아래 안내("1,000만원 이하")는 기존 그대로 보여
// 준다. 그리고 이 값이 범위 밖이 되는 순간 계산기 쪽(MortarCalculator.tsx)이 결과
// 공유 버튼 자체를 숨긴다(canShare 판정) — 그래서 "공유 버튼이 보이는 상태"에서는
// 화면 값과 계산값이 항상 같다(둘 다 범위 안의 값이거나 둘 다 비어 있다).
//
// 화면에 보이는 값(NumberField가 그리는 값)은 이 훅과 무관하게 그대로 form의 값을
// 쓴다 — 사용자가 999999999를 쳤으면 칸에는 999999999가 그대로 보인다(적은 값을
// 지우지 않는다). 이 훅이 돌려주는 값은 "계산에 실제로 넣을 값"에만 쓴다.
//
// 작성일: 2026년 09월 29일 · 개정(직전값 대신 undefined로): 2026년 09월 30일
// ──────────────────────────────────────────────

'use client';

import { isWithinRange } from './inputRanges';

/**
 * value가 [min,max] 범위 안이면 그 값을 그대로 돌려주고, 범위를 벗어나면 undefined
 * (안 넣은 것과 같음)를 돌려준다. 빈 값(undefined)은 애초에 "아직 안 넣음"이라
 * 그대로 undefined를 돌려준다(0원 계산과 같은 뜻).
 *
 * 더 이상 "직전에 있었던 유효값"을 기억하지 않는다 — 타이핑 도중 거쳐 간 값을 계산에
 * 쓰면 사용자가 실제로 의도한 적 없는 금액으로 계산되는 사고가 나기 때문이다(위 설명
 * 참고). 훅 이름은 예전 그대로 두지만(이 파일을 쓰는 곳이 한 군데뿐이라 이름을 굳이
 * 안 바꿨다) 동작은 "직전값 유지"가 아니라 "범위 밖이면 비움"으로 완전히 바뀌었다.
 */
export function useLastValidNumber(value: number | undefined, min: number, max: number): number | undefined {
  return isWithinRange(value, min, max) ? value : undefined;
}
