// ──────────────────────────────────────────────
// 재단 모듈 공용 — 올림 계산 도우미
//
// 이 파일이 하는 일:
//   재단 계산에서 쓰는 "올림"을 컴퓨터 소수점 오차에 걸리지 않게 해 준다.
//
// 왜 필요한가 (2026-09-10 검사관 지적):
//   컴퓨터는 소수를 정확히 못 담는다. 딱 떨어져야 하는 나눗셈이
//     2.145 ÷ 0.143 = 15.000000000000002
//   처럼 아주 조금 크게 나오는 일이 생긴다.
//   그대로 Math.ceil 하면 15열이면 될 것을 16열로 세어 자재가 한 줄 더 나간다.
//   같은 일이 덧셈에서도 생긴다 — 1.1 + 0.1 = 1.2000000000000002 → 1.3m 로 올라간다.
//
//   그래서 올리기 전에 아주 작은 값(1e-9)을 먼저 빼 준다.
//   1e-9 m = 1나노미터라 실제 자재 계산에는 아무 영향이 없고,
//   소수점 오차(보통 1e-16 안팎)만 정확히 걷어 낸다.
//
// 작성일: 2026년 09월 10일
// ──────────────────────────────────────────────

/** 소수점 오차를 걷어 내기 위해 올림 전에 빼 주는 아주 작은 값 */
export const CEIL_EPSILON = 1e-9;

/**
 * 소수점 오차에 안 걸리는 올림.
 * 예) ceilSafe(15.000000000000002) = 15  (그냥 Math.ceil 이면 16)
 *     ceilSafe(15.2)               = 16
 */
export function ceilSafe(n: number): number {
  return Math.ceil(n - CEIL_EPSILON);
}

/**
 * 소수점 첫째 자리까지 남기는 올림 (자재는 모자라면 안 되니 항상 올린다).
 * 예) ceilSafe1(1.2000000000000002) = 1.2  (그냥 올림이면 1.3)
 *     ceilSafe1(1.21)               = 1.3
 */
export function ceilSafe1(n: number): number {
  return Math.ceil(n * 10 - CEIL_EPSILON) / 10;
}
