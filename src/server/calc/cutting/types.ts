//
// 설계 원칙 (설계 정본 0절, 집사 2026-08-28):
//   "로스율은 추정 퍼센트가 아니라 실제로 잘라 보고 계산한다."
//   규격이 있는 자재는 전부 재단 시뮬레이션으로 로스를 뽑고,
//   퍼센트 추정은 실측 치수가 없을 때만 쓰는 폴백이다.
//
// 자재 유형별 재단 규칙 (설계 정본 0절 표):
//   | 유형       | 규격                 | 재단 규칙                                   | 적용 |
//   | rollWall   | 폭·길이·리피트        | 벽 높이 + 리피트 손실 → 롤당 폭 수          | 벽지·시트필름 |
//   | sheet      | 폭×길이·박스당 장 수  | 열 수·열당 장 수·자투리 재사용·방향 2안 비교 | 마루·데코타일·타일 |
//   | rollFloor  | 롤 폭·길이           | 방 폭 대비 이음선 수·이음 방향·롤 m 수       | 장판 |
//   | fabric     | 원단 폭·주름 배수     | 창 폭 × 배수 ÷ 원단 폭 = 폭 수              | 커튼·속커튼 |
//   | linear     | 단위 길이            | 둘레 ÷ 단위 길이(올림), 이음 최소화          | 걸레받이·몰딩·레일 |
//
// 이번 단계에서는 rollWall 만 구현하고 나머지는 인터페이스와 TODO 스텁만 둔다.
//
// 작성일: 2026년 08월 28일
// ──────────────────────────────────────────────

/**
 * 로스를 어떻게 구했는지. 화면에 그대로 붙는 꼬리표다.
 *   실제 — 실측 치수로 잘라 보고 구했다
 *   추정 — 평형만 있어 표준품셈 할증으로 잡았다
 *   면적 — 면적을 직접 입력받아 실별 배분 없이 재단 규격으로만 구했다
 */
export type LossMode = '실제' | '추정' | '면적';

/** 재단 유형 (자재 종류별 규칙 이름) */
export type CuttingKind = 'rollWall' | 'sheet' | 'rollFloor' | 'fabric' | 'linear';

/** 모든 재단 계산이 똑같이 돌려주는 결과 모양 */
export interface CuttingResult {
  /** 어떤 재단 규칙으로 계산했는지 */
  kind: CuttingKind;
  /** 구매해야 하는 수량 (롤·박스·m 등 — 이미 올림 완료) */
  units: number;
  /** units 의 단위 이름 (롤·박스·m …) */
  unitName: string;
  /** 로스를 실제로 잘라 봐서 구했는지, 퍼센트로 추정했는지 */
  lossMode: LossMode;
  /**
   * 재단 기준 로스율 (%). 잘라서 버리는 자투리만 센 값.
   * 실제 모드: (재단해서 쓴 면적 - 시공 면적) ÷ 시공 면적
   * 추정 모드: 표준품셈 정배지 할증 등 고정 퍼센트
   */
  lossPct: number;
  /**
   * 구매 기준 로스율 (%). 롤 수를 올림하면서 남는 잉여까지 포함한 값.
   * (구매 수량 × 단위당 면적 - 시공 면적) ÷ 시공 면적
   */
  purchaseLossPct: number;
  /** 실제 시공 면적 (㎡). 길이형 자재는 m 를 넣는다. */
  workAmount: number;
  /** 화면 "구성 보기"에 그대로 붙일 근거 문장 */
  basis: string;
  /** 계산 중간값 (디버깅·검증용. 소비자 응답에는 넣지 않는다) */
  detail?: Record<string, number>;
}

/** 재단 계산 함수의 공통 모양 */
export type CuttingFn<TInput> = (input: TInput) => CuttingResult;
