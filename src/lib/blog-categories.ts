// [왜 이렇게 만들었나]
// 글마다 붙어있는 태그(tags)는 검색 노출용 롱테일 키워드라서
// 65편에 태그 종류가 418개나 됩니다. ("34평 인테리어 비용", "25평 올수리 견적" ...)
// 태그를 그대로 칩으로 만들면 418개 칩이 생겨서 못 씁니다.
// 그래서 사람이 고를 만한 주제 묶음 8개를 만들고,
// "글 제목 + 글 태그"를 한 덩어리 글자로 붙인 다음
// 아래 keywords(신호 단어) 중 하나라도 들어있으면 그 묶음에 넣습니다.
//
// [규칙]
// - 한 글이 여러 카테고리에 동시에 들어갈 수 있습니다. (예: 욕실 타일 = 욕실 + 바닥·벽)
// - 띄어쓰기는 무시하고 비교합니다. ("샷시 교체" 와 "샷시교체" 를 같게 봄)
// - 어느 카테고리에도 안 걸리는 글이 없도록 keywords를 짰습니다.
//   (새 글이 추가됐는데 안 걸리면, 그 글은 "전체"에서만 보입니다 — 사라지진 않아요)
// ──────────────────────────────────────────────

/** 카테고리 한 개의 생김새 */
export interface BlogCategory {
  id: string; // URL 쿼리(?cat=)에 들어갈 영문 키
  label: string; // 화면에 보이는 한글 이름
  keywords: string[]; // 이 단어가 제목/태그에 있으면 이 카테고리로 분류
}

/**
 * 띄어쓰기·가운뎃점·괄호 같은 걸 없애고 소문자로 통일.
 * 한국어는 띄어쓰기가 제각각이라("샷시비용" vs "샷시 비용")
 * 비교 전에 전부 붙여버리는 게 가장 잘 맞습니다.
 */
export function normalizeKo(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\s·・,.\-—–_()[\]{}'"`~!?:;/\\|]/g, "");
}

