/** 미리 정규화해둔 키워드 표 (매번 다시 계산하지 않으려고) */
const NORMALIZED = BLOG_CATEGORIES.map((c) => ({
  id: c.id,
  keys: c.keywords.map(normalizeKo),
}));

/**
 * 글 하나가 어떤 카테고리들에 속하는지 판정.
 * @param title 글 제목
 * @param tags  글 태그 배열
 * @returns 속하는 카테고리 id 배열 (없으면 빈 배열)
 */
export function detectCategories(title: string, tags: string[]): string[] {
  // 제목과 태그를 한 줄로 붙이고 띄어쓰기를 없앤 "검사용 글자 덩어리"
  const hay = normalizeKo(`${title} ${tags.join(" ")}`);
  return NORMALIZED.filter((c) => c.keys.some((k) => hay.includes(k))).map((c) => c.id);
}
