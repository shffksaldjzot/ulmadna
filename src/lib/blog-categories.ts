/** id로 카테고리 찾기 — 없으면 undefined (허브 페이지에서 404 처리) */
export function getCategory(id: string): BlogCategory | undefined {
  return BLOG_CATEGORIES.find((c) => c.id === id);
}

/** id로 허브 글월 찾기 — 새 카테고리에 글월을 아직 안 적었을 때를 대비한 기본값 포함 */
export function getCategoryCopy(id: string): BlogCategoryCopy {
  const found = BLOG_CATEGORY_COPY[id];
  if (found) return found;
  const label = getCategory(id)?.label ?? "인테리어";
  return {
    seoTitle: `${label} 정보 모음 | 얼마드나 블로그`,
    seoDesc: `${label} 관련 인테리어 비용·시공 정보를 모았습니다.`,
    intro: `${label} 주제로 정리한 글을 모았습니다.`,
  };
}

/** 미리 정규화해둔 키워드 표 (매번 다시 계산하지 않으려고) */
const NORMALIZED = BLOG_CATEGORIES.map((c) => ({
  id: c.id,
  keys: c.keywords.map(normalizeKo),
}));

/**
 * 글 하나가 어떤 카테고리들에 속하는지 판정.
 * @param title 글 제목
 * @param tags  글 태그 배열
 * @returns 속하는 카테고리 id 배열 (없으면 빈 배열)
 */
export function detectCategories(title: string, tags: string[]): string[] {
  // 제목과 태그를 한 줄로 붙이고 띄어쓰기를 없앤 "검사용 글자 덩어리"
  const hay = normalizeKo(`${title} ${tags.join(" ")}`);
  return NORMALIZED.filter((c) => c.keys.some((k) => hay.includes(k))).map((c) => c.id);
}
